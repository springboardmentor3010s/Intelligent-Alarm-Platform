from datetime import datetime

from sqlalchemy import (
    Column,
    Integer,
    String,
    Boolean,
    DateTime,
    ForeignKey,
)

from ..database import Base


class Recommendation(Base):
    """
    Stores AI-generated personalized recommendations for each user.

    Generated by the recommendation engine based on ACTUAL behavioral data
    (challenge history, snooze activity, wake consistency).
    Never hardcoded — always derived from real DB records.
    """

    __tablename__ = "recommendations"

    id = Column(Integer, primary_key=True, index=True)

    user_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=False,
        index=True,
    )

    # Structured recommendation fields
    title = Column(String(200), nullable=False)
    reason = Column(String(1000), nullable=False)
    suggested_action = Column(String(500), nullable=False)
    supporting_metric = Column(String(300), nullable=True)

    # Category: difficulty | snooze_control | consistency | cognitive_performance
    #           | positive_reinforcement | onboarding | general
    category = Column(String(50), nullable=False, default="general")

    # Priority: high | medium | low
    priority = Column(String(20), nullable=False, default="medium")

    # Lifecycle tracking
    is_acted_upon = Column(Boolean, default=False, nullable=False)
    is_dismissed = Column(Boolean, default=False, nullable=False)

    created_at = Column(DateTime, default=datetime.utcnow)
    expires_at = Column(DateTime, nullable=True)
