# Creates a .env file with freshly generated random secrets. Never overwrites an existing .env.
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root ".env"
if (Test-Path $envFile) { Write-Host ".env already exists - keeping it."; exit 0 }

function New-Secret([int]$len) {
  $chars = [char[]]"ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789"
  do {
    $bytes = New-Object byte[] $len
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $s = -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
  } until ($s -cmatch '[A-Za-z]' -and $s -match '\d')
  return $s
}

$secretKey = New-Secret 64
$pg        = New-Secret 28
$mongo     = New-Secret 28
$admin     = New-Secret 16
$demo      = New-Secret 16

